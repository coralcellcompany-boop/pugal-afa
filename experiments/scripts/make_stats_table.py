"""Pre-registered paired "win" test (notes/experiments.md, "Compute budget and stopping rule").

A win of method A over B on a dataset: the mean paired acc-AUC difference over the 5 seeds (same seed = same
split, classifier and kNN pool) exceeds its standard deviation, and the two-sided Wilcoxon signed-rank test over
all dataset x seed pairs is significant at 0.05. Per-dataset cells: mean paired difference +- its std, with
"+" (win), "-" (loss: the mirror condition) or no mark. Last rows: win/no-difference/loss counts and the pooled
Wilcoxon p-value. Values are read from results/*.json; nothing is typed by hand.
Run: `uv run python papers/pugal-afa/experiments/scripts/make_stats_table.py [OUT]` (from the experiments dir:
`uv run python scripts/make_stats_table.py`).
"""
from __future__ import annotations

import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

from scipy.stats import wilcoxon

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "paper" / "tables" / "paired_tests.tex"
MAIN = ["cube", "cube_nm", "synmix_0.5", "diabetes", "miniboone", "physionet", "bank", "actg175", "ckd"]
LABEL = {"cube": "CUBE", "cube_nm": "CUBE-NM", "synmix_0.5": "SynMix(0.5)", "diabetes": "Diabetes",
         "miniboone": "MiniBooNE", "physionet": "PhysioNet", "bank": "Bank", "actg175": "ACTG175", "ckd": "CKD"}
PAIRS = [("pugal", "greedy", "PUGAL $-$ greedy"), ("pugal", "la2", "PUGAL $-$ LA2"), ("la2", "greedy", "LA2 $-$ greedy")]
SEEDS = range(5)
METRIC = "acc_auc"
ALPHA = 0.05


def value(config: str, seed: int) -> float:
    path = RES / f"{config}_seed{seed}.json"
    if not path.exists():
        raise SystemExit(f"error: missing {path.name}")
    return float(json.loads(path.read_text())["metrics"][METRIC])


def paired(a: str, b: str, ds: str) -> list[float]:
    return [value(f"{ds}_{a}", s) - value(f"{ds}_{b}", s) for s in SEEDS]


def main() -> int:
    cols, summary, sources = [], [], []
    for a, b, _ in PAIRS:
        diffs = {ds: paired(a, b, ds) for ds in MAIN}
        pooled = [d for ds in MAIN for d in diffs[ds]]
        p = float(wilcoxon(pooled, alternative="two-sided").pvalue) if any(pooled) else 1.0
        sig = p < ALPHA
        cells, w, t, l = {}, 0, 0, 0
        for ds in MAIN:
            m, sd = statistics.mean(diffs[ds]), statistics.stdev(diffs[ds])
            mark = ""
            if sig and m > sd:
                mark, w = "^{+}", w + 1
            elif sig and m < -sd:
                mark, l = "^{-}", l + 1
            else:
                t += 1
            ms = f"{m:+.3f}".replace("-0.000", "+0.000")
            cells[ds] = f"${ms} \\pm {sd:.3f}{mark}$"
        cols.append(cells)
        summary.append((f"{w} / {t} / {l}", f"{p:.2g}"))
    for ds in MAIN:
        for a, b, _ in PAIRS:
            sources += [f"{ds}_{a}", f"{ds}_{b}"]
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_stats_table.py on {stamp} from results/<config>_seed0-4.json",
        f"% configs: {' '.join(sorted(set(sources)))}",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Paired acc-AUC differences over the five seeds (mean $\pm$ std of the per-seed difference). "
        r"$^{+}$/$^{-}$: pre-registered win/loss (mean difference beyond one std and pooled two-sided Wilcoxon "
        r"signed-rank test over all 45 dataset--seed pairs at $p < 0.05$; zero differences are dropped, as in "
        r"the standard test).}",
        r"\label{tab:paired_tests}",
        r"\small",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
        r"\begin{tabular}{l" + "c" * len(PAIRS) + "}",
        r"\toprule",
        "Dataset & " + " & ".join(lbl for _, _, lbl in PAIRS) + r" \\",
        r"\midrule",
        *[LABEL[ds] + " & " + " & ".join(c[ds] for c in cols) + r" \\" for ds in MAIN],
        r"\midrule",
        "Win / no difference / loss & " + " & ".join(s[0] for s in summary) + r" \\",
        "Wilcoxon $p$ (45 pairs) & " + " & ".join(s[1] for s in summary) + r" \\",
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
