"""Exploratory (post hoc, 2026-11-06): acquisitions needed to reach greedy's final accuracy.

For each dataset and seed, the target is greedy's test accuracy after the largest budget B (same seed = same
split, classifier and kNN pool). For each method, t* is the first budget t with acc_t >= target. Cells: median t*
over the seeds that reach the target, and how many of the 5 seeds reach it within B. Values are read from
results/*.json; nothing is typed by hand. Run from the experiments dir: `uv run python scripts/make_budget_table.py`.
"""
from __future__ import annotations

import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "paper" / "tables" / "budget_to_greedy.tex"
MAIN = ["cube", "cube_nm", "synmix_0.5", "diabetes", "miniboone", "physionet", "bank", "actg175", "ckd"]
LABEL = {"cube": "CUBE", "cube_nm": "CUBE-NM", "synmix_0.5": "SynMix(0.5)", "diabetes": "Diabetes",
         "miniboone": "MiniBooNE", "physionet": "PhysioNet", "bank": "Bank", "actg175": "ACTG175", "ckd": "CKD"}
METHODS = [("greedy", "Greedy"), ("la2", "Always-LA2"), ("pugal", "PUGAL")]
SEEDS = range(5)


def curve(config: str, seed: int) -> list[float]:
    path = RES / f"{config}_seed{seed}.json"
    if not path.exists():
        raise SystemExit(f"error: missing {path.name}")
    m = json.loads(path.read_text())["metrics"]
    ts = sorted(int(k[5:]) for k in m if k.startswith("acc_t"))
    return [float(m[f"acc_t{t}"]) for t in ts]


def main() -> int:
    rows = []
    for ds in MAIN:
        B = len(curve(f"{ds}_greedy", 0))
        cells = []
        for method, _ in METHODS:
            hits = []
            for s in SEEDS:
                target = curve(f"{ds}_greedy", s)[-1]
                acc = curve(f"{ds}_{method}", s)
                t = next((i + 1 for i, a in enumerate(acc) if a >= target), None)
                if t is not None:
                    hits.append(t)
            med = f"{statistics.median(hits):g}" if hits else "--"
            cells.append(f"{med} ({len(hits)}/5)")
        rows.append(f"{LABEL[ds]} & {B} & " + " & ".join(cells) + r" \\")
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    cfgs = " ".join(f"{ds}_{m}" for ds in MAIN for m, _ in METHODS)
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_budget_table.py on {stamp} from results/<config>_seed0-4.json",
        f"% configs: {cfgs}",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Exploratory (post hoc). Acquisitions needed to reach greedy's accuracy at the largest budget $B$ "
        r"on the same seed: median over the seeds that reach it, and the number of seeds (of 5) that reach it "
        r"within $B$. Test accuracy is not monotone in the budget, so greedy itself can reach its final value "
        r"before $B$.}",
        r"\label{tab:budget_to_greedy}",
        r"\small",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
        r"\begin{tabular}{lc" + "c" * len(METHODS) + "}",
        r"\toprule",
        "Dataset & $B$ & " + " & ".join(lbl for _, lbl in METHODS) + r" \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
