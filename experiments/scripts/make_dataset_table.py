"""Generate paper/tables/datasets.tex from the data loaders (seed 0). No number is typed by hand."""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import tomllib

from experiment.data import load_dataset

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "paper" / "tables" / "datasets.tex"
ROWS = [("cube", "CUBE"), ("cube_nm", "CUBE-NM"), ("synmix_0.5", "SynMix(0.5)"), ("diabetes", "Diabetes"),
        ("miniboone", "MiniBooNE"), ("physionet", "PhysioNet"), ("bank", "BankMarketing"), ("actg175", "ACTG175"),
        ("ckd", "CKD")]


def budget_and_cap(name: str) -> tuple[int, int | None]:
    cfg = tomllib.loads((ROOT / "configs" / f"{name}_pugal.toml").read_text())
    return cfg["budget"], cfg.get("test_cap")


def main() -> None:
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_dataset_table.py on "
        f"{datetime.now(timezone.utc).isoformat(timespec='seconds')} from the data loaders (seed 0) and configs/. Do not edit by hand.",
        r"\begin{table}[t]", r"\centering",
        r"\caption{Datasets (seed-0 split). $d$: features, actions: acquisition groups, $B$: budget, test: evaluated test instances per seed.}",
        r"\label{tab:datasets}", r"\begin{tabular}{lrrrrrrrl}", r"\toprule",
        r"Dataset & Train & Val & Test & $d$ & Actions & Classes & $B$ & Imbalanced \\", r"\midrule",
    ]
    for name, label in ROWS:
        data = load_dataset(name, 0, ROOT / "data")
        budget, cap = budget_and_cap(name)
        n_test = min(len(data.y_test), cap) if cap else len(data.y_test)
        lines.append(f"{label} & {len(data.y_train)} & {len(data.y_val)} & {n_test} & {data.X_train.shape[1]} & "
                     f"{len(data.groups)} & {data.n_classes} & {budget} & {'yes' if data.imbalanced else 'no'} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
