"""Compute table from runs/run_all.log (wall-clock job time per job kind) and the machine description.

Run from the experiments directory or anywhere: `uv run python scripts/make_compute_table.py --out ../paper/tables/compute.tex`.
Job wall-clock time is an upper bound on CPU time: each job is single-threaded, and it shared the machine with other load.
"""
from __future__ import annotations

import argparse
import platform
import re
import subprocess
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

LOG = Path(__file__).resolve().parents[1] / "runs" / "run_all.log"
KINDS = [("warm", "Classifier training and synergy screen"), ("la2ref", "Selection reference (always-LA2, validation)"),
         ("tune", "Hyperparameter selection (validation, seed 0)"), ("run", "Test runs (all methods, seeds, ablations)")]


def machine() -> str:
    if platform.system() == "Darwin":
        q = lambda k: subprocess.run(["sysctl", "-n", k], capture_output=True, text=True).stdout.strip()
        return f"{q('machdep.cpu.brand_string')}, {q('hw.physicalcpu')} cores, {int(q('hw.memsize')) // 2**30} GB"
    return f"{platform.processor() or platform.machine()}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--log", type=Path, default=LOG)
    args = ap.parse_args()
    secs, count = defaultdict(float), defaultdict(int)
    for m in re.finditer(r"\bok\s+(\w+):\S+\s+(\d+)s", args.log.read_text()):
        secs[m.group(1)] += float(m.group(2)); count[m.group(1)] += 1
    when = datetime.now(timezone.utc).isoformat(timespec="seconds")
    rows = [f"{label} & {count[k]} & {secs[k] / 3600:.1f} \\\\" for k, label in KINDS if count[k]]
    total_h = sum(secs.values()) / 3600
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_compute_table.py on {when} from runs/run_all.log. Do not edit by hand.",
        r"\begin{table}[t]", r"\centering",
        f"\\caption{{Compute. Job wall-clock hours, an upper bound on CPU-hours (single-threaded jobs on a shared machine: {machine()}).}}",
        r"\label{tab:compute}", r"\begin{tabular}{lrr}", r"\toprule", r"Job kind & Jobs & Hours \\", r"\midrule",
        *rows, r"\midrule", f"Total & {sum(count.values())} & {total_h:.1f} \\\\", r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} ({sum(count.values())} jobs, {total_h:.1f} h)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
