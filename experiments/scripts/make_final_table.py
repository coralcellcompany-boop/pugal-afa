"""Exploratory (post hoc, 2026-11-06, self-review 1): test accuracy at the largest budget B, the quantity whose
risk counterpart the theory of Sec. 3 optimises, next to acc-AUC (the pre-registered metric, an average over
budgets). Cells: mean +- std over the 5 seeds of acc_t<B>, plus the paired mean difference to greedy.
Values are read from results/*.json; nothing is typed by hand.
Run from the experiments dir: `uv run python scripts/make_final_table.py [OUT]`.
"""
from __future__ import annotations

import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "paper" / "tables" / "final_acc.tex"
DATASETS = ["cube", "cube_nm", "synmix_0.5", "synmix_1", "diabetes", "miniboone", "physionet", "bank", "actg175", "ckd"]
LABEL = {"cube": "CUBE", "cube_nm": "CUBE-NM", "synmix_0.5": "SynMix(0.5)", "synmix_1": "SynMix(1)",
         "diabetes": "Diabetes", "miniboone": "MiniBooNE", "physionet": "PhysioNet", "bank": "Bank",
         "actg175": "ACTG175", "ckd": "CKD"}
METHODS = [("greedy", "Greedy"), ("la2", "Always-LA2"), ("pugal", "PUGAL")]
SEEDS = range(5)


def final_acc(config: str, seed: int) -> float:
    path = RES / f"{config}_seed{seed}.json"
    if not path.exists():
        raise SystemExit(f"error: missing {path.name}")
    m = json.loads(path.read_text())["metrics"]
    B = max(int(k[5:]) for k in m if k.startswith("acc_t"))
    return float(m[f"acc_t{B}"])


def pm(values: list[float]) -> str:
    return f"{statistics.mean(values):.2f} $\\pm$ {statistics.stdev(values):.2f}"


def main() -> int:
    rows = []
    for ds in DATASETS:
        vals = {m: [final_acc(f"{ds}_{m}", s) for s in SEEDS] for m, _ in METHODS}
        diff = [a - b for a, b in zip(vals["la2"], vals["greedy"])]
        ms = f"{statistics.mean(diff):+.3f}".replace("-0.000", "+0.000")
        d = f"${ms} \\pm {statistics.stdev(diff):.3f}$"
        rows.append(f"{LABEL[ds]} & " + " & ".join(pm(vals[m]) for m, _ in METHODS) + f" & {d}" + r" \\")
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    cfgs = " ".join(f"{ds}_{m}" for ds in DATASETS for m, _ in METHODS)
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_final_table.py on {stamp} from results/<config>_seed0-4.json",
        f"% configs: {cfgs}",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Exploratory (post hoc). Test accuracy after the largest budget $B$ (mean $\pm$ std over five "
        r"seeds) and the paired difference between always-LA2 and greedy (mean $\pm$ std of the per-seed "
        r"difference).}",
        r"\label{tab:final_acc}",
        r"\small",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
        r"\begin{tabular}{l" + "r" * (len(METHODS) + 1) + "}",
        r"\toprule",
        "Dataset & " + " & ".join(lbl for _, lbl in METHODS) + r" & LA2 $-$ greedy \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
