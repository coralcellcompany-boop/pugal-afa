"""H3 table: Spearman correlation between dataset-level predictors and the acc-AUC gain over greedy.

Column 1 is the pre-registered H3 test (9 main datasets, gain of always-LA2). The other columns are the
exploratory X3 analysis (notes/experiments.md, "Exploratory follow-up"): gain of PUGAL, and the SynMix rho-sweep.
Values per dataset are seed means read from results/*.json; a constant predictor has no Spearman ("--").
Run from the repo root or anywhere: `uv run python papers/pugal-afa/experiments/scripts/make_h3_table.py [OUT]`.
"""
from __future__ import annotations

import glob
import json
import math
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "paper" / "tables" / "h3_correlation.tex"
MAIN = ["cube", "cube_nm", "synmix_0.5", "diabetes", "miniboone", "physionet", "bank", "actg175", "ckd"]
SWEEP = ["synmix_0", "synmix_0.1", "synmix_0.25", "synmix_0.5", "synmix_0.75", "synmix_1"]
PREDICTORS = [("nmi", "NMI"), ("nmi_proxy", "NMI proxy"), ("gamma_hat", r"$-\hat\gamma$ (min)"),
              ("gamma_mean", r"$-\bar\gamma$ (mean)")]
SIGN = {"gamma_hat": -1.0, "gamma_mean": -1.0}   # low submodularity ratio = more need for lookahead


def mean_metric(config: str, key: str) -> float:
    vals = [json.loads(Path(p).read_text())["metrics"].get(key) for p in sorted(glob.glob(str(RES / f"{config}_seed*.json")))]
    vals = [v for v in vals if v is not None and math.isfinite(v)]
    if not vals:
        raise SystemExit(f"error: no finite {key} in results/{config}_seed*.json")
    return statistics.mean(vals)


def ranks(x: list[float]) -> list[float]:
    order = sorted(range(len(x)), key=lambda i: x[i])
    r = [0.0] * len(x)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and x[order[j + 1]] == x[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2
        i = j + 1
    return r


def spearman(a: list[float], b: list[float]) -> float:
    ra, rb = ranks(a), ranks(b)
    ma, mb = statistics.mean(ra), statistics.mean(rb)
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    den = math.sqrt(sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb))
    return num / den if den > 0 else float("nan")


def column(datasets: list[str], method: str) -> dict[str, float]:
    gain = [mean_metric(f"{d}_{method}", "acc_auc") - mean_metric(f"{d}_greedy", "acc_auc") for d in datasets]
    return {k: spearman([SIGN.get(k, 1.0) * mean_metric(f"{d}_gatequality", k) for d in datasets], gain)
            for k, _ in PREDICTORS}


def main() -> int:
    cols = [("main", "la2", MAIN), ("main", "pugal", MAIN), ("sweep", "la2", SWEEP), ("sweep", "pugal", SWEEP)]
    table = [column(ds, m) for _, m, ds in cols]
    fmt = lambda v: "--" if not math.isfinite(v) else f"${v:.2f}$"
    rows = [" & ".join([label] + [fmt(t[k]) for t in table]) + r" \\" for k, label in PREDICTORS]
    when = datetime.now(timezone.utc).isoformat(timespec="seconds")
    lines = [
        f"% AUTO-GENERATED by scripts/make_h3_table.py on {when} from experiments/results/*.json. Do not edit by hand; re-run the script.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Spearman correlation between dataset-level predictors and the acc-AUC gain over greedy "
        r"(seed means). First column: the pre-registered H3 test (9 main datasets, always-LA2). Other columns: "
        r"exploratory, added after the main results (PUGAL's gain; SynMix $\rho$-sweep, " + f"{len(SWEEP)}" +
        r" values). ``--'': the predictor is constant.}",
        r"\label{tab:h3}",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r" & \multicolumn{2}{c}{9 main datasets} & \multicolumn{2}{c}{SynMix $\rho$-sweep} \\",
        r"Predictor & LA2 & PUGAL & LA2 & PUGAL \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
