"""Compute ratios: classifier evaluations per instance of always-LA2 over PUGAL (synergy gate) and of PUGAL over
greedy, as ratios of seed means, per main dataset. Values are read from results/*.json; nothing is typed by hand.
Run from the experiments dir: `uv run python scripts/make_ratio_table.py [OUT]`.
"""
from __future__ import annotations

import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "paper" / "tables" / "compute_ratio.tex"
MAIN = ["cube", "cube_nm", "synmix_0.5", "diabetes", "miniboone", "physionet", "bank", "actg175", "ckd"]
LABEL = {"cube": "CUBE", "cube_nm": "CUBE-NM", "synmix_0.5": "SynMix(0.5)", "diabetes": "Diabetes",
         "miniboone": "MiniBooNE", "physionet": "PhysioNet", "bank": "Bank", "actg175": "ACTG175", "ckd": "CKD"}
RATIOS = [("la2", "pugal", "Always-LA2 / PUGAL"), ("pugal", "greedy", "PUGAL / greedy")]


def mean_evals(config: str) -> float:
    paths = sorted(RES.glob(f"{config}_seed*.json"))
    if len(paths) != 5:
        raise SystemExit(f"error: expected 5 seeds for {config}, found {len(paths)}")
    return statistics.mean(float(json.loads(p.read_text())["metrics"]["evals_per_inst"]) for p in paths)


def main() -> int:
    rows = []
    for ds in MAIN:
        cells = [f"{mean_evals(f'{ds}_{a}') / mean_evals(f'{ds}_{b}'):.1f}" for a, b, _ in RATIOS]
        rows.append(f"{LABEL[ds]} & " + " & ".join(cells) + r" \\")
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    cfgs = " ".join(sorted({f"{ds}_{m}" for ds in MAIN for a, b, _ in RATIOS for m in (a, b)}))
    lines = [
        f"% AUTO-GENERATED by experiments/scripts/make_ratio_table.py on {stamp} from results/<config>_seed0-4.json",
        f"% configs: {cfgs}",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Ratios of classifier evaluations per instance (ratios of the five-seed means; "
        r"\cref{tab:main_evals} gives the counts).}",
        r"\label{tab:compute_ratio}",
        r"\small",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{%",
        r"\begin{tabular}{l" + "r" * len(RATIOS) + "}",
        r"\toprule",
        "Dataset & " + " & ".join(lbl for _, _, lbl in RATIOS) + r" \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
